CREATE TABLE JOGADOR
( 
    ID_JOGADOR NUMBER(10,0) NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    POSICAO VARCHAR2(100),
    BI VARCHAR2(100),
    CONSTRAINT PK_JOGADOR PRIMARY KEY (ID_JOGADOR)
);

CREATE TABLE CONTRATADO
(
    ID_JOGADOR NUMBER(10,0) NOT NULL,
    DATA_INICIO DATE NOT NULL,
    DATA_FIM DATE NOT NULL,
    CONSTRAINT PK_CONTRATADO PRIMARY KEY (ID_JOGADOR, DATA_INICIO),
    CONSTRAINT FK_CONTRATADO_REF_JOGADOR FOREIGN KEY (ID_JOGADOR) 
        REFERENCES JOGADOR(ID_JOGADOR),
    CONSTRAINT CK_CONTRATADO_DATA_FIM CHECK (DATA_FIM > DATA_INICIO)
);

--Primary Key (JOGADOR)
--→ Identifica unicamente cada jogador.

--Primary Key composta (CONTRATADO)
--→ Garante que um jogador não tenha dois contratos iniciando na mesma data.

--Foreign Key (CONTRATADO → JOGADOR)
--→ Garante que todo contrato esteja ligado a um jogador existente.


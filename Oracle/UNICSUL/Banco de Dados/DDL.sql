🧱 O que é uma CONSTRAINT?

CONSTRAINT é uma regra que você impõe ao banco de dados para garantir a integridade dos dados.

👉 Em outras palavras:

é o banco dizendo “esses dados só entram se respeitarem essas regras”.

Essas regras evitam:

Dados duplicados

Valores inválidos

Relacionamentos quebrados

Registros sem sentido no mundo real
